  function displayValue(value) {
    if (
      value === undefined ||
      value === null ||
      value === ""
    ) {
      return "未指定";
    }

    if (Array.isArray(value)) {
      return value.length
        ? value.join("、")
        : "未指定";
    }

    return String(value);
  }


  function addConfirmRow(
    container,
    label,
    value
  ) {
    if (!container) return;

    const row =
      document.createElement("div");

    row.className =
      "confirm-row";

    const labelElement =
      document.createElement("dt");

    labelElement.className =
      "confirm-label";

    labelElement.textContent =
      label;

    const valueElement =
      document.createElement("dd");

    valueElement.className =
      "confirm-value";

    valueElement.textContent =
      displayValue(value);

    row.append(
      labelElement,
      valueElement
    );

    container.appendChild(row);
  }


