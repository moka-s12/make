  function generateReceiptNumber() {
    const now =
      new Date();

    const year =
      String(
        now.getFullYear()
      ).slice(-2);

    const month =
      String(
        now.getMonth() + 1
      ).padStart(2, "0");

    const day =
      String(
        now.getDate()
      ).padStart(2, "0");

    const random =
      Math.random()
        .toString(36)
        .slice(2, 7)
        .toUpperCase();

    return (
      `ONE-${year}${month}${day}-${random}`
    );
  }


