  /* =========================================================
     EXCLUSIVE CHECKBOX
  ========================================================= */

  function handleExclusiveCheckbox(
    changedInput
  ) {

    if (
      !changedInput ||
      changedInput.type !==
        "checkbox" ||
      !changedInput.name ||
      !changedInput.checked
    ) {
      return;
    }


    const group =
      $$(
        `input[type="checkbox"][name="${changedInput.name}"]`
      );


    const isExclusive =
      changedInput.hasAttribute(
        "data-exclusive"
      ) ||
      changedInput.value ===
        "なし" ||
      changedInput.value ===
        "おまかせ";


    if (isExclusive) {

      group.forEach((input) => {

        if (
          input !== changedInput
        ) {
          input.checked = false;
        }

      });

      return;
    }


    group.forEach((input) => {

      const exclusive =
        input.hasAttribute(
          "data-exclusive"
        ) ||
        input.value === "なし" ||
        input.value === "おまかせ";


      if (exclusive) {
        input.checked = false;
      }

    });
  }


