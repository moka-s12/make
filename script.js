  function fileToBase64(file) {
    return new Promise(
      (resolve, reject) => {
        const reader =
          new FileReader();

        reader.addEventListener(
          "load",
          () => {
            const result =
              String(
                reader.result || ""
              );

            const commaIndex =
              result.indexOf(",");

            resolve(
              commaIndex >= 0
                ? result.slice(
                    commaIndex + 1
                  )
                : result
            );
          }
        );

        reader.addEventListener(
          "error",
          () => {
            reject(
              new Error(
                `${file.name} の読み込みに失敗しました`
              )
            );
          }
        );

        reader.readAsDataURL(file);
      }
    );
  }


  async function getUploadFiles(
    inputId,
    category
  ) {
    const input =
      $(`#${inputId}`);

    if (
      !input ||
      input.type !== "file"
    ) {
      return [];
    }

    const files =
      [...(input.files || [])];

    const uploads = [];

    for (const file of files) {

      if (
        file.size >
        MAX_UPLOAD_FILE_SIZE
      ) {
        throw new Error(
          `${file.name} は5MB以下の画像にしてね`
        );
      }

      const base64 =
        await fileToBase64(file);

      uploads.push({
        category,
        name: file.name,
        type:
          file.type ||
          "application/octet-stream",
        size: file.size,
        base64
      });
    }

    return uploads;
  }


