  function setupFilePreview(input) {
    if (!input || input.type !== "file") {
      return;
    }

    const preview =
      document.querySelector(
        `[data-preview-for="${input.id}"]`
      );

    if (!preview) return;

    input.addEventListener(
      "change",
      () => {
        const files =
          [...(input.files || [])];

        preview.innerHTML = "";

        if (!files.length) {
          preview.hidden = true;
          preview.style.display = "none";
          return;
        }

        preview.hidden = false;
        preview.style.display = "";

        files.forEach((file) => {
          const item =
            document.createElement("div");

          item.className =
            "file-preview-item";

          if (
            file.type.startsWith("image/")
          ) {
            const reader =
              new FileReader();

            reader.addEventListener(
              "load",
              () => {
                const image =
                  document.createElement(
                    "img"
                  );

                image.src =
                  String(reader.result);

                image.alt =
                  file.name;

                image.className =
                  "file-preview-image";

                item.prepend(image);
              }
            );

            reader.readAsDataURL(file);
          }

          const name =
            document.createElement("span");

          name.className =
            "file-preview-name";

          name.textContent =
            file.name;

          item.appendChild(name);

          preview.appendChild(item);
        });
      }
    );
  }


  $$('input[type="file"]')
    .forEach(setupFilePreview);


