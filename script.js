  async function sendOrderToSpreadsheet(
    order
  ) {
    const response =
      await fetch(
        GAS_URL,
        {
          method: "POST",

          headers: {
            "Content-Type":
              "text/plain;charset=utf-8"
          },

          body:
            JSON.stringify(order),

          redirect:
            "follow"
        }
      );


    if (!response.ok) {
      throw new Error(
        `Googleへの送信に失敗しました (${response.status})`
      );
    }


    const text =
      await response.text();


    if (!text.trim()) {
      return {
        ok: true
      };
    }


    try {
      const result =
        JSON.parse(text);

      if (
        result?.ok === false
      ) {
        throw new Error(
          result.error ||
          "Google側でエラーが発生しました"
        );
      }

      return (
        result || {
          ok: true
        }
      );

    } catch (error) {

      /*
        Apps Script側のリダイレクト等で
        JSON以外が返った場合。

        HTTP自体が成功していれば
        送信済みとして扱う。
      */

      if (
        error instanceof Error &&
        error.message !==
          "Unexpected end of JSON input" &&
        !error.message.startsWith(
          "Unexpected token"
        )
      ) {
        throw error;
      }

      console.warn(
        "GAS response was not JSON:",
        text
      );

      return {
        ok: true,
        nonJsonResponse: true
      };
    }
  }


